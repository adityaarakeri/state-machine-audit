#!/usr/bin/env node
// Generates single-file adapters for agents that do not load SKILL.md
// folders natively. SKILL.md stays the single source of truth; never
// hand-edit anything in dist/.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, SKILLS_DIR, listSkills, parseSkill, yamlString } from "./lib.mjs";

const DIST = join(ROOT, "dist");
rmSync(DIST, { recursive: true, force: true });

const BANNER = "<!-- Generated by scripts/build.mjs from skills/. Do not edit by hand. -->";

/** Inline every referenced file so the result works as one self-contained prompt. */
function bundle(dir, body) {
  const refs = [...new Set([...body.matchAll(/`(references\/[^`]+\.md)`/g)].map((m) => m[1]))];
  const appendix = refs
    .map((ref) => {
      const text = readFileSync(join(SKILLS_DIR, dir, ref), "utf8").trim();
      return `\n\n---\n\n<!-- inlined: ${ref} -->\n\n${text.replace(/^# /m, "## Appendix: ")}`;
    })
    .join("");
  // Point the agent at the appendix instead of files that will not exist.
  const rewritten = body.replace(/`references\/([^`]+)\.md`/g, "the appendix for `$1` below");
  return rewritten + appendix;
}

const agentsSections = [];

for (const dir of listSkills()) {
  const { data, body } = parseSkill(join(SKILLS_DIR, dir, "SKILL.md"));
  const full = bundle(dir, body);

  // 1. Plain prompt: paste into any chat-style agent.
  write(`prompt/${dir}.md`, `${BANNER}\n\n${full}\n`);

  // 2. Cursor project rule (manual attach via @rule name).
  write(
    `cursor/.cursor/rules/${dir}.mdc`,
    `---\ndescription: ${yamlString(data.description)}\nalwaysApply: false\n---\n${BANNER}\n\n${full}\n`,
  );

  // 3. GitHub Copilot / VS Code prompt file (run with /<name> in chat). Uses the
  //    current `agent:` key; the older `mode:` key is no longer documented.
  write(
    `copilot/.github/prompts/${dir}.prompt.md`,
    `---\nname: ${yamlString(data.name)}\ndescription: ${yamlString(data.description)}\nagent: agent\n---\n${BANNER}\n\n${full}\n`,
  );

  agentsSections.push(
    `## Skill: ${data.name}\n\n**When to use:** ${data.description}\n\nOnly follow this section when the user asks for it.\n\n${full}`,
  );
}

// 4. AGENTS.md / GEMINI.md fallback bundle (Codex, Gemini CLI, Windsurf, Amp, etc.).
const agentsMd = `${BANNER}\n\n# Agent skills\n\n${agentsSections.join("\n\n---\n\n")}\n`;
write("AGENTS.md", agentsMd);
write("GEMINI.md", agentsMd);

function write(rel, content) {
  const out = join(DIST, rel);
  mkdirSync(join(out, ".."), { recursive: true });
  writeFileSync(out, content);
  console.log(`  wrote dist/${rel}`);
}
console.log("✔ build complete");
